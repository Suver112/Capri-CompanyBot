"""Compatibility launcher for the old Capri_Piper_MOS_Fix_Studio shortcut.

Starting with Capri Beta 2.5, the MOS-safe training script is generated by
capri_voice_studio.write_training_script itself. Do not monkey-patch it here:
the earlier string-rewriting MOS fix was incompatible with Beta 2.4's ARGS
array and could break a working WSL trainer.
"""
from __future__ import annotations
import os
from pathlib import Path


def main() -> int:
    os.chdir(Path(__file__).resolve().parent)
    from capri_voice_studio import main as studio_main
    return studio_main()


if __name__ == '__main__':
    raise SystemExit(main())
